"""Collect every evaluation in logs/ into markdown tables (docs/RESULTS_AUTO.md).
Re-run after new evals finish:  python3 tools/make_tables.py
Sources: per-task lines "tXX sr=..." in logs/eval_*.log, abl_*.log, ctl_*.log; per-episode details in the matching .json.
"""
import glob, json, math, os, re
from collections import defaultdict

R = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
L = f"{R}/logs"
TASK = {13: "RC3", 14: "RC5", 15: "RC9", 50: "RC3-L", 51: "RC5-L", 52: "RC9-L", 53: "Shape3", 54: "Shape5", 55: "Shape9",
        56: "SAC3x2", 57: "SAC3x3", 58: "SAC5x3", 59: "Bunch3", 60: "Bunch5", 61: "Bunch7", 62: "Seq3", 63: "Seq5", 64: "Seq7",
        65: "Chain3", 66: "Chain5", 67: "Chain7", 68: "ShellTouch", 69: "ShellColorLamp", 70: "BlinkE", 71: "BlinkM", 72: "BlinkH",
        82: "TimedE", 83: "TimedM", 84: "TimedH"}
FAMILY = [("RememberColor", (50, 51, 52)), ("RememberShape", (53, 54, 55)), ("ShapeAndColor", (56, 57, 58)),
          ("BunchOfColors", (59, 60, 61)), ("SeqOfColors", (62, 63, 64)), ("ChainOfColors", (65, 66, 67)),
          ("ShellGame", (68, 69)), ("BlinkCount", (70, 71, 72)), ("TimedTransfer", (82, 83, 84))]
LONG = [t for _, ts in FAMILY for t in ts]
AMB = {frozenset(p) for p in ((0, 6), (3, 7), (5, 8))}      # env colour pairs the VLM names alike (red/maroon, yellow/orange, cyan/teal)


def wilson(k, n, z=1.96):
    if n == 0: return (float("nan"),) * 2
    p = k / n; d = 1 + z * z / n; c = p + z * z / (2 * n); h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n))
    return (c - h) / d, (c + h) / d


def runs():
    """(model, step) -> {tid: [per-episode success]} from json files (falls back to log sr= lines)."""
    out = defaultdict(dict)
    pats = [(r"eval_db_(.+)_(\d{6})", None), (r"eval_long_(.+)_(\d{6})_m\d", None), (r"eval_long_(.+)_g\d", "final"),
            (r"eval_x52_(.+)", "x52"), (r"abl_(.+)", "abl"), (r"ctl_(.+)", "ctl")]
    for f in sorted(glob.glob(f"{L}/*.log")):
        b = os.path.basename(f)[:-4]
        for p, kind in pats:
            m = re.fullmatch(p, b)
            if not m: continue
            model = m.group(1); step = m.group(2) if kind is None else kind
            j = f[:-4] + ".json"
            got = {}
            if os.path.exists(j):
                try:
                    for r in json.load(open(j))["results"]:
                        got[r["tid"]] = r
                except Exception:
                    pass
            for ln in open(f, errors="ignore"):
                mm = re.match(r"\s*t(\d+) sr=([0-9.]+)", ln)
                if mm and int(mm.group(1)) not in got:
                    got[int(mm.group(1))] = dict(sr=float(mm.group(2)), successes=None)
            for t, r in got.items():
                out[(model, step)][t] = r
            break
    return out


def fmt(r):
    return "–" if r is None else f"{r['sr']:.2f}"


def main():
    D = runs()
    md = ["# Results (auto-generated by tools/make_tables.py — do not edit by hand)", ""]
    # 1. RC-Long joint (t5x) models at 20k
    md += ["## RC-Long, joint 3-task models, 20k steps (50 episodes per task)", "",
           "| model | RC3-L | RC5-L | RC9-L | RC9-L pooled n | RC9-L pooled SR [95% CI] |", "|---|---|---|---|---|---|"]
    for m in ["pi05_t5x_base", "pi05_t5x_v2", "pi05_t5x_v3", "pi05_t5x_v4", "pi05_t5x_v5", "pi05_t5x_v6", "pi05_t5x_vis", "pi05_t5x_oracle"]:
        r = D.get((m, "020000"), {})
        if not r: continue
        s52 = list(r.get(52, {}).get("successes") or [])
        x = D.get((m, "x52"), {}).get(52)
        if x and x.get("successes"): s52 += x["successes"]
        lo, hi = wilson(sum(s52), len(s52))
        md.append(f"| {m} | {fmt(r.get(50))} | {fmt(r.get(51))} | {fmt(r.get(52))} | {len(s52)} | "
                  f"{sum(s52) / max(1, len(s52)):.3f} [{lo:.2f}, {hi:.2f}] |")
    # 2. RC9-L error decomposition from closest approach
    md += ["", "## RC9-L selection (which cube the gripper approached closest; 50 episodes)", "",
           "right = closest cube has the cue colour; amb = confused within red/maroon, yellow/orange, cyan/teal; other = any other cube.",
           "Success additionally needs the touch condition, so success <= right.", "",
           "| model | success | right | amb | other |", "|---|---|---|---|---|"]
    for (m, s), r in sorted(D.items()):
        if 52 not in r or not r[52].get("progress") or s not in ("020000", "abl", "ctl"): continue
        c = defaultdict(int)
        for p in r[52]["progress"]:
            k = min(range(len(p["mind"])), key=lambda i: p["mind"][i])
            c["right" if k == p["true"] else "amb" if frozenset((k, p["true"])) in AMB else "other"] += 1
        md.append(f"| {m} {s} | {sum(r[52]['successes'])} | {c['right']} | {c['amb']} | {c['other']} |")
    # 3. test-time note swaps and content controls
    md += ["", "## Eval-only note swaps / controls", "", "| run | task | SR |", "|---|---|---|"]
    for (m, s), r in sorted(D.items()):
        if s in ("abl", "ctl"):
            for t, x in sorted(r.items()): md.append(f"| {s} {m} | {TASK.get(t, t)} | {x['sr']:.2f} |")
    # 4. 26 Long tasks
    long_runs = sorted(k for k, r in D.items() if k[0].startswith("pi05_long"))
    if long_runs:
        md += ["", "## 26 -Long tasks, one joint model per method (50 episodes per task)", "",
               "| family | task | " + " | ".join(f"{m.replace('pi05_long_', '')} {s}" for m, s in long_runs) + " |",
               "|---|---|" + "---|" * len(long_runs)]
        for fam, ts in FAMILY:
            for t in ts:
                md.append(f"| {fam} | {TASK[t]} | " + " | ".join(fmt(D[k].get(t)) for k in long_runs) + " |")
        row, row13 = [], []
        done = [t for t in LONG if all(t in D[k] for k in long_runs)]
        for k in long_runs:
            v = [D[k][t]["sr"] for t in LONG if t in D[k]]
            row.append(f"{sum(v) / len(v):.3f} ({len(v)}/26)" if v else "–")
            row13.append(f"{sum(D[k][t]['sr'] for t in done) / max(1, len(done)):.3f}")
        md.append("| **mean** | evaluated tasks | " + " | ".join(row) + " |")
        md.append(f"| **mean** | {len(done)} tasks done by all | " + " | ".join(row13) + " |")
    # 5. other runs
    md += ["", "## Other runs", "", "| model | step | task | SR |", "|---|---|---|---|"]
    for (m, s), r in sorted(D.items()):
        if m.startswith(("pi05_long", "pi05_t5x")) or s in ("abl", "ctl", "x52"): continue
        for t, x in sorted(r.items()): md.append(f"| {m} | {s} | {TASK.get(t, t)} | {x['sr']:.2f} |")
    os.makedirs(f"{R}/docs", exist_ok=True)
    open(f"{R}/docs/RESULTS_AUTO.md", "w").write("\n".join(md) + "\n")
    print("\n".join(md))


if __name__ == "__main__":
    main()
