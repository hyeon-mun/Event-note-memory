"""Recompute main-table rates and paired episode bootstrap intervals from logs.

Run from any directory: python3 paper/audit_results.py
Uses the Python standard library; does not modify evaluation logs.
Intervals condition on the existing single trained checkpoint per method.
"""
from pathlib import Path
import json
import math
import random

ROOT = Path(__file__).resolve().parents[1]


def episodes(filename, task):
    obj = json.loads((ROOT / "logs" / filename).read_text())
    result = next(r for r in obj["results"] if r["tid"] == task)
    values = result["successes"]
    assert values and all(isinstance(x, bool) for x in values)
    assert abs(sum(values) / len(values) - result["sr"]) < 1e-8
    start = obj["args"].get("start_seed", 4242424242)
    offset = obj["args"].get("ep_lo", 0)
    return {start + offset + i: int(v) for i, v in enumerate(values)}


def main_episodes(model, task, extended=False):
    result = episodes(f"eval_db_pi05_t5x_{model}_020000.json", task)
    if extended:
        more = episodes(f"eval_x52_pi05_t5x_{model}.json", task)
        assert not result.keys() & more.keys(), "Overlapping evaluation seeds"
        result.update(more)
    return result


def wilson(values):
    n, k = len(values), sum(values)
    p, z = k / n, 1.96
    d = 1 + z * z / n
    c = p + z * z / (2 * n)
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n))
    return (c - h) / d, (c + h) / d


def paired(label, reference, intervention):
    assert reference.keys() == intervention.keys(), "Unmatched evaluation seeds"
    differences = [intervention[k] - reference[k] for k in sorted(reference)]
    rng, n = random.Random(20261105), len(differences)
    samples = sorted(sum(rng.choices(differences, k=n)) / n for _ in range(20000))
    lo, hi = samples[500], samples[19499]
    return f"| {label} | {n} | {sum(differences)/n:+.3f} | [{lo:+.3f}, {hi:+.3f}] |"


def main():
    lines = ["# Recomputed episode statistics", "",
             "Generated by `python3 paper/audit_results.py`. Evaluation JSONs are the source.",
             "Rates and intervals condition on one checkpoint per method; training-seed variability is not measured.", "",
             "| Method | RC3-L | RC5-L | RC9-L, n=150 | Wilson 95% CI |",
             "|---|---|---|---|---|"]
    for model in ("base", "v2", "v3", "v4", "v6", "oracle"):
        results = [main_episodes(model, t, extended=t == 52) for t in (50, 51, 52)]
        rates = [sum(x.values()) / len(x) for x in results]
        lo, hi = wilson(list(results[-1].values()))
        lines.append(f"| {model} | {rates[0]:.2f} | {rates[1]:.2f} | {rates[2]:.3f} | [{lo:.2f}, {hi:.2f}] |")
    lines += ["", "Paired percentile bootstrap: 20,000 resamples of matched episode seeds, RNG seed 20261105.",
              "Differences are intervention minus reference, in success-rate units. No multiplicity correction.", "",
              "| Comparison | Episodes | Difference | Paired bootstrap 95% CI |",
              "|---|---|---|---|"]
    for task in (50, 51, 52):
        lines.append(paired(f"v6 minus no memory, t{task}", main_episodes("base", task, task == 52),
                            main_episodes("v6", task, task == 52)))
    for trained, writer in (("v4", "v3"), ("v3", "v4")):
        lines.append(paired(f"{trained} policy: {writer} writer minus native writer",
                            main_episodes(trained, 52), episodes(f"abl_{trained}model_{writer}notes.json", 52)))
    output = Path(__file__).with_name("RESULTS_AUDIT.md")
    output.write_text("\n".join(lines) + "\n")
    print(output.read_text())


if __name__ == "__main__":
    main()
